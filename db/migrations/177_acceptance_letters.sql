BEGIN;

-- One conditional and one unconditional letter per application. The issued letter is the
-- generated PDF the coordinator stamps outside the system; the student only ever receives the
-- stamped copy. Coordinator names and emails are copied in so the audit trail survives a
-- coordinator account being deleted.
CREATE TABLE public.acceptance_letters (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    application_id INT NOT NULL REFERENCES public.inboundapplication(application_id) ON DELETE CASCADE,
    student_id INT NOT NULL REFERENCES public.incomingstudentauth(student_id) ON DELETE CASCADE,
    letter_type VARCHAR(13) NOT NULL CHECK (letter_type IN ('Conditional', 'Unconditional')),
    storage_bucket TEXT NOT NULL DEFAULT 'acceptance-letters' CHECK (storage_bucket = 'acceptance-letters'),
    file_path VARCHAR(255) NOT NULL CHECK (length(btrim(file_path)) > 0),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    issued_by INT REFERENCES public.coordinator(coordinator_id) ON DELETE SET NULL,
    issued_by_name VARCHAR(255) NOT NULL CHECK (length(btrim(issued_by_name)) > 0),
    issued_by_email VARCHAR(255) NOT NULL CHECK (length(btrim(issued_by_email)) > 0),
    stamped_file_path VARCHAR(255) CHECK (stamped_file_path IS NULL OR length(btrim(stamped_file_path)) > 0),
    stamped_at TIMESTAMPTZ,
    stamped_by INT REFERENCES public.coordinator(coordinator_id) ON DELETE SET NULL,
    stamped_by_name VARCHAR(255),
    stamped_by_email VARCHAR(255),
    CONSTRAINT acceptance_letters_one_per_type UNIQUE (application_id, letter_type),
    CONSTRAINT acceptance_letters_stamp_complete CHECK (
        (stamped_file_path IS NULL AND stamped_at IS NULL AND stamped_by_name IS NULL AND stamped_by_email IS NULL)
        OR (stamped_file_path IS NOT NULL AND stamped_at IS NOT NULL AND stamped_by_name IS NOT NULL AND stamped_by_email IS NOT NULL)
    )
);

CREATE INDEX acceptance_letters_student_idx ON public.acceptance_letters (student_id);

-- Rows are written only by issue_acceptance_letter and save_stamped_acceptance_letter, so
-- there are no insert, update or delete policies.
ALTER TABLE public.acceptance_letters ENABLE ROW LEVEL SECURITY;

CREATE POLICY "KU coordinators can read acceptance letters"
ON public.acceptance_letters
FOR SELECT
TO authenticated
USING ((SELECT public.is_ku_coordinator()));

CREATE POLICY "Incoming students can read their stamped acceptance letters"
ON public.acceptance_letters
FOR SELECT
TO authenticated
USING (
    stamped_file_path IS NOT NULL
    AND EXISTS (
        SELECT 1
        FROM public.incomingstudentauth AS student
        WHERE student.student_id = acceptance_letters.student_id
          AND student.user_id = (SELECT auth.uid())
    )
);

CREATE POLICY "Maintenance blocks acceptance letter reads"
ON public.acceptance_letters AS RESTRICTIVE FOR SELECT TO anon, authenticated
USING ((SELECT public.get_maintenance_mode()) IS FALSE);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'acceptance-letters',
    'acceptance-letters',
    FALSE,
    10485760,
    ARRAY['application/pdf', 'image/jpeg', 'image/png']
)
ON CONFLICT (id) DO UPDATE
SET public = FALSE,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "KU coordinators can upload acceptance letters" ON storage.objects;
DROP POLICY IF EXISTS "KU coordinators can read acceptance letters" ON storage.objects;
DROP POLICY IF EXISTS "KU coordinators can delete unused acceptance letters" ON storage.objects;
DROP POLICY IF EXISTS "Incoming students can read their stamped acceptance letters" ON storage.objects;

CREATE POLICY "KU coordinators can upload acceptance letters"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'acceptance-letters'
    AND (SELECT public.is_ku_coordinator())
);

CREATE POLICY "KU coordinators can read acceptance letters"
ON storage.objects
FOR SELECT
TO authenticated
USING (
    bucket_id = 'acceptance-letters'
    AND (SELECT public.is_ku_coordinator())
);

-- Lets the page remove an upload when saving the letter fails. A file a letter points at stays.
CREATE POLICY "KU coordinators can delete unused acceptance letters"
ON storage.objects
FOR DELETE
TO authenticated
USING (
    bucket_id = 'acceptance-letters'
    AND (SELECT public.is_ku_coordinator())
    AND NOT EXISTS (
        SELECT 1 FROM public.acceptance_letters AS letter
        WHERE storage.objects.name IN (letter.file_path, letter.stamped_file_path)
    )
);

-- The unstamped letter is not an official document, so only the stamped copy is readable.
CREATE POLICY "Incoming students can read their stamped acceptance letters"
ON storage.objects
FOR SELECT
TO authenticated
USING (
    bucket_id = 'acceptance-letters'
    AND EXISTS (
        SELECT 1
        FROM public.acceptance_letters AS letter
        JOIN public.incomingstudentauth AS student ON student.student_id = letter.student_id
        WHERE letter.stamped_file_path = storage.objects.name
          AND student.user_id = (SELECT auth.uid())
    )
);

CREATE OR REPLACE FUNCTION public.issue_acceptance_letter(
    requested_application_id INT,
    requested_letter_type TEXT,
    requested_file_path TEXT
)
RETURNS public.acceptance_letters
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    application_row public.inboundapplication;
    coordinator_row public.coordinator;
    letter_row public.acceptance_letters;
    prefix TEXT;
BEGIN
    IF NOT public.is_ku_coordinator() THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Only a KU coordinator can issue acceptance letters';
    END IF;
    IF public.testing_change_allowed('inboundapplication', requested_application_id::TEXT) IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'This application cannot be changed in the current mode';
    END IF;
    IF requested_letter_type IS NULL OR requested_letter_type NOT IN ('Conditional', 'Unconditional') THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Choose a conditional or unconditional acceptance letter';
    END IF;

    SELECT * INTO application_row
    FROM public.inboundapplication
    WHERE application_id = requested_application_id
    FOR UPDATE;
    -- A letter states the approval the application has now, so a conditional letter cannot be
    -- issued after the approval became unconditional, nor the other way round.
    IF NOT FOUND
       OR application_row.application_status NOT IN ('Accepted', 'Approved')
       OR application_row.approval_type IS DISTINCT FROM requested_letter_type THEN
        RAISE EXCEPTION USING ERRCODE = '22023',
            MESSAGE = format('A %s acceptance letter needs an application with %s approval', lower(requested_letter_type), lower(requested_letter_type));
    END IF;
    IF application_row.student_id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'This application has no student account to receive the letter';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.acceptance_letters
        WHERE application_id = requested_application_id AND letter_type = requested_letter_type
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23505',
            MESSAGE = format('A %s acceptance letter was already issued for this application', lower(requested_letter_type));
    END IF;

    prefix := application_row.student_id::TEXT || '/' || requested_application_id::TEXT || '/' || lower(requested_letter_type) || '/';
    IF requested_file_path IS NULL
       OR left(requested_file_path, length(prefix)) IS DISTINCT FROM prefix
       OR NOT EXISTS (
           SELECT 1 FROM storage.objects
           WHERE bucket_id = 'acceptance-letters' AND name = requested_file_path
       ) THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Upload the acceptance letter for this application first';
    END IF;

    SELECT * INTO coordinator_row FROM public.coordinator WHERE user_id = auth.uid();

    INSERT INTO public.acceptance_letters (
        application_id, student_id, letter_type, file_path,
        issued_by, issued_by_name, issued_by_email
    )
    VALUES (
        requested_application_id, application_row.student_id, requested_letter_type, requested_file_path,
        coordinator_row.coordinator_id, coordinator_row.name, coordinator_row.email
    )
    RETURNING * INTO letter_row;
    RETURN letter_row;
END;
$$;

REVOKE ALL ON FUNCTION public.issue_acceptance_letter(INT, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.issue_acceptance_letter(INT, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.save_stamped_acceptance_letter(
    requested_letter_id INT,
    requested_file_path TEXT
)
RETURNS public.acceptance_letters
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    letter_row public.acceptance_letters;
    coordinator_row public.coordinator;
    prefix TEXT;
BEGIN
    IF NOT public.is_ku_coordinator() THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Only a KU coordinator can upload a stamped acceptance letter';
    END IF;

    SELECT * INTO letter_row
    FROM public.acceptance_letters
    WHERE id = requested_letter_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Acceptance letter not found';
    END IF;
    IF public.testing_change_allowed('inboundapplication', letter_row.application_id::TEXT) IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'This application cannot be changed in the current mode';
    END IF;
    -- The student has already been sent the stamped copy, so it is not replaced silently.
    IF letter_row.stamped_file_path IS NOT NULL THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'The stamped letter was already sent to the student';
    END IF;

    prefix := letter_row.student_id::TEXT || '/' || letter_row.application_id::TEXT || '/' || lower(letter_row.letter_type) || '/';
    IF requested_file_path IS NULL
       OR requested_file_path = letter_row.file_path
       OR left(requested_file_path, length(prefix)) IS DISTINCT FROM prefix
       OR NOT EXISTS (
           SELECT 1 FROM storage.objects
           WHERE bucket_id = 'acceptance-letters' AND name = requested_file_path
       ) THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Upload the stamped acceptance letter first';
    END IF;

    SELECT * INTO coordinator_row FROM public.coordinator WHERE user_id = auth.uid();

    UPDATE public.acceptance_letters
    SET stamped_file_path = requested_file_path,
        stamped_at = now(),
        stamped_by = coordinator_row.coordinator_id,
        stamped_by_name = coordinator_row.name,
        stamped_by_email = coordinator_row.email
    WHERE id = requested_letter_id
    RETURNING * INTO letter_row;

    INSERT INTO public.updates (inbound_application_id, details)
    VALUES (
        letter_row.application_id,
        format('Your %s acceptance letter from Kuwait University has been issued. Download it from your application page.',
            lower(letter_row.letter_type))
    );
    RETURN letter_row;
END;
$$;

REVOKE ALL ON FUNCTION public.save_stamped_acceptance_letter(INT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.save_stamped_acceptance_letter(INT, TEXT) TO authenticated;

NOTIFY pgrst, 'reload schema';

COMMIT;
