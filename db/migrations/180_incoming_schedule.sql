BEGIN;

-- A KU coordinator sets the courses an incoming student takes on the student's approved
-- application; the semester and its dates come from that application's KU semester. Times are
-- Kuwait wall-clock times, the way KU publishes its timetable, so they carry no time zone.
CREATE TABLE public.inbound_schedule_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    application_id INT NOT NULL REFERENCES public.inboundapplication(application_id) ON DELETE CASCADE,
    student_id INT NOT NULL REFERENCES public.incomingstudentauth(student_id) ON DELETE CASCADE,
    -- Empty for a course outside the CBA list, which then has no subject page.
    subject_code CHAR(7) REFERENCES public.subjects(course_code) ON DELETE SET NULL,
    course_display_code VARCHAR(20) NOT NULL CHECK (length(btrim(course_display_code)) > 0),
    course_name VARCHAR(255) NOT NULL CHECK (length(btrim(course_name)) > 0),
    meeting_days TEXT[] NOT NULL CHECK (
        cardinality(meeting_days) > 0
        AND array_ndims(meeting_days) = 1
        AND meeting_days <@ ARRAY['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
    ),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room VARCHAR(100) NOT NULL CHECK (length(btrim(room)) > 0),
    instructor VARCHAR(255) NOT NULL CHECK (length(btrim(instructor)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inbound_schedule_items_time_order CHECK (start_time < end_time)
);

CREATE INDEX inbound_schedule_items_application_idx ON public.inbound_schedule_items (application_id);
CREATE INDEX inbound_schedule_items_student_idx ON public.inbound_schedule_items (student_id);

CREATE OR REPLACE FUNCTION public.prepare_inbound_schedule_item()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    week_days CONSTANT TEXT[] := ARRAY['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
    subject_row public.subjects;
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- The student comes from the application, so a course can never reach another student.
        NEW.student_id := (
            SELECT application.student_id FROM public.inboundapplication AS application
            WHERE application.application_id = NEW.application_id
        );
        NEW.created_at := now();
    ELSE
        IF NEW.application_id IS DISTINCT FROM OLD.application_id THEN
            RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'A scheduled course cannot be moved to another application';
        END IF;
        NEW.student_id := OLD.student_id;
        NEW.created_at := OLD.created_at;
    END IF;

    -- A CBA course takes its code and name from the catalogue, so the schedule and the subject
    -- page always agree.
    IF NEW.subject_code IS NOT NULL THEN
        SELECT * INTO subject_row FROM public.subjects WHERE course_code = NEW.subject_code;
        IF FOUND THEN
            NEW.course_display_code := subject_row.course_display_code;
            NEW.course_name := subject_row.course_name;
        END IF;
    END IF;

    -- Stored in week order without repeats, so every reader lists the days the same way.
    IF NEW.meeting_days <@ week_days THEN
        NEW.meeting_days := ARRAY(
            SELECT week.day
            FROM unnest(week_days) WITH ORDINALITY AS week(day, position)
            WHERE week.day = ANY (NEW.meeting_days)
            ORDER BY week.position
        );
    END IF;

    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.prepare_inbound_schedule_item() FROM PUBLIC;

CREATE TRIGGER inbound_schedule_items_prepare
BEFORE INSERT OR UPDATE ON public.inbound_schedule_items
FOR EACH ROW EXECUTE FUNCTION public.prepare_inbound_schedule_item();

ALTER TABLE public.inbound_schedule_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.inbound_schedule_items FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.inbound_schedule_items TO authenticated;

CREATE POLICY "KU coordinators can read schedules"
ON public.inbound_schedule_items
FOR SELECT
TO authenticated
USING ((SELECT public.is_ku_coordinator()));

CREATE POLICY "Incoming students can read their own schedule"
ON public.inbound_schedule_items
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.incomingstudentauth AS student
        JOIN public.inboundapplication AS application ON application.student_id = student.student_id
        WHERE student.student_id = inbound_schedule_items.student_id
          AND application.application_id = inbound_schedule_items.application_id
          AND application.application_status IN ('Accepted', 'Approved')
          AND student.user_id = (SELECT auth.uid())
    )
);

-- Only an approved application gets a schedule. testing_change_allowed refuses during
-- maintenance and, in testing mode, accepts only test applications; their courses are deleted
-- with them when testing ends, so this table needs no testing tracker of its own.
CREATE POLICY "KU coordinators can add schedule courses"
ON public.inbound_schedule_items
FOR INSERT
TO authenticated
WITH CHECK (
    (SELECT public.is_ku_coordinator())
    AND public.testing_change_allowed('inboundapplication', application_id::TEXT)
    AND EXISTS (
        SELECT 1 FROM public.inboundapplication AS application
        WHERE application.application_id = inbound_schedule_items.application_id
          AND application.application_status IN ('Accepted', 'Approved')
    )
);

CREATE POLICY "KU coordinators can edit schedule courses"
ON public.inbound_schedule_items
FOR UPDATE
TO authenticated
USING (
    (SELECT public.is_ku_coordinator())
    AND public.testing_change_allowed('inboundapplication', application_id::TEXT)
)
WITH CHECK (
    (SELECT public.is_ku_coordinator())
    AND public.testing_change_allowed('inboundapplication', application_id::TEXT)
    AND EXISTS (
        SELECT 1 FROM public.inboundapplication AS application
        WHERE application.application_id = inbound_schedule_items.application_id
          AND application.application_status IN ('Accepted', 'Approved')
    )
);

CREATE POLICY "KU coordinators can remove schedule courses"
ON public.inbound_schedule_items
FOR DELETE
TO authenticated
USING (
    (SELECT public.is_ku_coordinator())
    AND public.testing_change_allowed('inboundapplication', application_id::TEXT)
);

CREATE POLICY "Maintenance blocks schedule reads"
ON public.inbound_schedule_items AS RESTRICTIVE FOR SELECT TO anon, authenticated
USING ((SELECT public.get_maintenance_mode()) IS FALSE);

NOTIFY pgrst, 'reload schema';

COMMIT;
