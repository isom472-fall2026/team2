-- Issue #101: emergency contacts belong to an incoming student and can be saved before applying.
CREATE POLICY "Incoming students can read their own emergency contact"
ON public.emergency_contact FOR SELECT TO authenticated
USING (EXISTS (
    SELECT 1 FROM public.incomingstudentauth AS student
    WHERE student.student_id = emergency_contact.student_id AND student.user_id = (SELECT auth.uid())
));

CREATE OR REPLACE FUNCTION public.set_inbound_emergency_contact()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    -- A new application and a simultaneous contact save must agree on the link.
    IF TG_OP = 'INSERT' AND NEW.original_application_id IS NULL THEN
        PERFORM 1 FROM public.incomingstudentauth
        WHERE student_id = NEW.student_id FOR SHARE;
    END IF;

    IF TG_OP = 'UPDATE'
       AND NEW.student_id IS NOT DISTINCT FROM OLD.student_id
       AND NEW.emergency_contact IS NOT DISTINCT FROM OLD.emergency_contact THEN
        RETURN NEW;
    END IF;

    -- Trusted seed inserts can retain the links on legacy contacts without an owner.
    IF TG_OP = 'INSERT' AND auth.uid() IS NULL AND NEW.emergency_contact IS NOT NULL THEN
        RETURN NEW;
    END IF;

    SELECT contact_id INTO NEW.emergency_contact
    FROM public.emergency_contact WHERE student_id = NEW.student_id;
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.set_inbound_emergency_contact() FROM PUBLIC;

CREATE TRIGGER inboundapplication_set_emergency_contact
BEFORE INSERT OR UPDATE OF student_id, emergency_contact ON public.inboundapplication
FOR EACH ROW EXECUTE FUNCTION public.set_inbound_emergency_contact();

CREATE OR REPLACE FUNCTION public.save_my_emergency_contact(
    requested_name TEXT, requested_phone TEXT, requested_email TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    owner_id INT;
    saved_contact_id INT;
BEGIN
    SELECT student_id INTO owner_id
    FROM public.incomingstudentauth
    WHERE user_id = auth.uid()
    FOR NO KEY UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'An incoming student account is required';
    END IF;
    IF public.testing_change_allowed('incomingstudentauth', owner_id::TEXT) IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Emergency contacts cannot be changed in the current mode';
    END IF;

    requested_name := nullif(btrim(requested_name), '');
    requested_email := nullif(btrim(requested_email), '');
    IF requested_name IS NULL OR requested_name !~ '[^[:space:]]' OR char_length(requested_name) > 255 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Enter a contact name of up to 255 characters.';
    END IF;
    IF requested_phone IS NULL OR requested_phone !~ '^[+][1-9][0-9]{6,14}$' THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Enter a valid phone number with a country code.';
    END IF;
    IF requested_email IS NOT NULL AND (
        char_length(requested_email) > 255
        OR requested_email !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Enter a valid contact email address.';
    END IF;

    SELECT contact_id INTO saved_contact_id FROM public.emergency_contact WHERE student_id = owner_id;
    IF FOUND THEN
        IF public.testing_change_allowed('emergency_contact', saved_contact_id::TEXT) IS DISTINCT FROM TRUE THEN
            RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'This emergency contact cannot be changed in the current mode';
        END IF;
        UPDATE public.emergency_contact
        SET name = requested_name, phone_number = requested_phone, email = requested_email
        WHERE contact_id = saved_contact_id;
    ELSE
        INSERT INTO public.emergency_contact (student_id, name, phone_number, email)
        VALUES (owner_id, requested_name, requested_phone, requested_email)
        RETURNING contact_id INTO saved_contact_id;
    END IF;

    -- An edit may replace the application while the contact is being saved.
    -- Lock the current rows first so the update can see any newly committed version.
    PERFORM 1 FROM public.inboundapplication AS application
    WHERE application.student_id = owner_id
      AND application.application_status <> 'Modified'
      AND public.testing_change_allowed('inboundapplication', application.application_id::TEXT)
    ORDER BY application.application_id
    FOR UPDATE;

    UPDATE public.inboundapplication AS application
    SET emergency_contact = saved_contact_id
    WHERE application.student_id = owner_id
      AND application.application_status <> 'Modified'
      AND application.emergency_contact IS DISTINCT FROM saved_contact_id
      AND public.testing_change_allowed('inboundapplication', application.application_id::TEXT);
END;
$$;

REVOKE ALL ON FUNCTION public.save_my_emergency_contact(TEXT, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.save_my_emergency_contact(TEXT, TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.find_emergency_contacts(search_term TEXT)
RETURNS TABLE (
    student_id INT, student_name TEXT, student_email TEXT,
    contact_name TEXT, contact_phone TEXT, contact_email TEXT
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF public.is_ku_coordinator() IS DISTINCT FROM TRUE
       OR public.get_maintenance_mode() IS DISTINCT FROM FALSE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Emergency contact lookup is unavailable';
    END IF;

    search_term := lower(btrim(search_term));
    IF search_term IS NULL OR search_term = '' THEN
        RETURN;
    END IF;

    RETURN QUERY
    SELECT student.student_id, student.name::TEXT, student.student_email::TEXT,
           contact.name::TEXT, contact.phone_number::TEXT, contact.email::TEXT
    FROM public.incomingstudentauth AS student
    JOIN LATERAL (
        -- Keep previously linked contacts discoverable after the ownership column is added.
        SELECT candidate.name, candidate.phone_number, candidate.email
        FROM (
            SELECT owned.name, owned.phone_number, owned.email, TRUE AS owned_contact,
                   NULL::TIMESTAMP AS application_date, NULL::INT AS application_id
            FROM public.emergency_contact AS owned
            WHERE owned.student_id = student.student_id
            UNION ALL
            SELECT legacy.name, legacy.phone_number, legacy.email, FALSE,
                   application.created_at, application.application_id
            FROM public.inboundapplication AS application
            JOIN public.emergency_contact AS legacy ON legacy.contact_id = application.emergency_contact
            WHERE application.student_id = student.student_id AND legacy.student_id IS NULL
        ) AS candidate
        ORDER BY candidate.owned_contact DESC, candidate.application_date DESC NULLS LAST,
                 candidate.application_id DESC
        LIMIT 1
    ) AS contact ON TRUE
    WHERE strpos(lower(student.name), search_term) > 0
       OR strpos(lower(student.student_email), search_term) > 0
    ORDER BY student.name, student.student_id
    LIMIT 50;
END;
$$;

REVOKE ALL ON FUNCTION public.find_emergency_contacts(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.find_emergency_contacts(TEXT) TO authenticated;

COMMIT;
