CREATE TABLE public.outbound_course_choices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES public.outboundapplication(application_id) ON DELETE CASCADE,
    subject_code CHAR(7) REFERENCES public.subjects(course_code) ON DELETE SET NULL,
    course_display_code VARCHAR(30) NOT NULL CHECK (length(btrim(course_display_code)) > 0),
    course_title VARCHAR(255) NOT NULL CHECK (length(btrim(course_title)) > 0),
    credits NUMERIC NOT NULL CHECK (credits > 0 AND credits < 'Infinity'::NUMERIC),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX outbound_course_choices_application_idx ON public.outbound_course_choices(application_id, id);

ALTER TABLE public.outbound_course_choices ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.outbound_course_choices FROM anon, authenticated;
GRANT SELECT ON public.outbound_course_choices TO authenticated;

CREATE POLICY "Students and KU coordinators can read outbound course choices"
ON public.outbound_course_choices FOR SELECT TO authenticated
USING (
    (SELECT public.is_ku_coordinator()) OR EXISTS (
        SELECT 1 FROM public.outboundapplication AS application
        JOIN public.kustudentauth AS student ON student.student_id = application.student_id
        WHERE application.application_id = outbound_course_choices.application_id
          AND student.user_id = (SELECT auth.uid())
    )
);
CREATE POLICY "Maintenance blocks outbound course choice reads"
ON public.outbound_course_choices AS RESTRICTIVE FOR SELECT TO anon, authenticated
USING ((SELECT public.get_maintenance_mode()) IS FALSE);

-- Every write locks the application, as does its decision function. This serializes the
-- eight-course check and prevents a save racing with application approval.
CREATE OR REPLACE FUNCTION public.save_outbound_course_choice(
    requested_application_id BIGINT,
    requested_choice_id BIGINT DEFAULT NULL,
    requested_subject_code TEXT DEFAULT NULL,
    requested_course_code TEXT DEFAULT NULL,
    requested_course_title TEXT DEFAULT NULL,
    requested_credits NUMERIC DEFAULT NULL
)
RETURNS public.outbound_course_choices
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    application_row public.outboundapplication;
    result public.outbound_course_choices;
    chosen_code TEXT;
    chosen_title TEXT;
BEGIN
    SELECT * INTO application_row FROM public.outboundapplication
    WHERE application_id = requested_application_id FOR UPDATE;
    IF NOT FOUND OR NOT EXISTS (
        SELECT 1 FROM public.kustudentauth
        WHERE student_id = application_row.student_id AND user_id = auth.uid()
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Only the applicant can change this course list';
    END IF;
    IF public.testing_change_allowed('outboundapplication', requested_application_id::TEXT) IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Courses cannot be changed in the current mode';
    END IF;
    IF application_row.application_status NOT IN ('Submitted', 'In Review', 'Pending Interview') THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'This course list is read-only after approval or while the application is not awaiting a decision';
    END IF;
    IF requested_credits IS NULL OR NOT (requested_credits > 0 AND requested_credits < 'Infinity'::NUMERIC) THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Enter credits as a positive number';
    END IF;
    IF requested_subject_code IS NOT NULL THEN
        SELECT course_display_code, course_name INTO chosen_code, chosen_title
        FROM public.subjects WHERE course_code = requested_subject_code;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Choose a course from the KU catalog';
        END IF;
    ELSE
        chosen_code := NULLIF(btrim(requested_course_code), '');
        chosen_title := NULLIF(btrim(requested_course_title), '');
    END IF;
    IF chosen_code IS NULL OR chosen_title IS NULL OR length(chosen_code) > 30 OR length(chosen_title) > 255 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Enter a course code (up to 30 characters) and title (up to 255 characters)';
    END IF;
    IF requested_choice_id IS NULL THEN
        IF (SELECT count(*) FROM public.outbound_course_choices WHERE application_id = requested_application_id) >= 8 THEN
            RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'You can list up to 8 courses';
        END IF;
        INSERT INTO public.outbound_course_choices(application_id, subject_code, course_display_code, course_title, credits)
        VALUES (requested_application_id, requested_subject_code, chosen_code, chosen_title, requested_credits)
        RETURNING * INTO result;
    ELSE
        UPDATE public.outbound_course_choices
        SET subject_code = requested_subject_code, course_display_code = chosen_code,
            course_title = chosen_title, credits = requested_credits, updated_at = clock_timestamp()
        WHERE id = requested_choice_id AND application_id = requested_application_id
        RETURNING * INTO result;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Course not found on this application';
        END IF;
    END IF;
    RETURN result;
END;
$$;
REVOKE ALL ON FUNCTION public.save_outbound_course_choice(BIGINT, BIGINT, TEXT, TEXT, TEXT, NUMERIC) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.save_outbound_course_choice(BIGINT, BIGINT, TEXT, TEXT, TEXT, NUMERIC) TO authenticated;

