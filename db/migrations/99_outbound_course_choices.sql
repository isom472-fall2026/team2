-- Graph-only applicants have no sign-in account or uploads. They are invented records,
-- confined to a registered testing cycle and deleted by the existing testing cleanup.
CREATE OR REPLACE FUNCTION public.seed_testing_cycle_applications(requested_cycle_id INT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    cycle_row public.exchange_cycle;
    universities INT[];
    countries INT[];
    coordinator_ids INT[] := '{}';
    university_id INT;
    generated_coordinator_id INT;
    nomination_id BIGINT;
    inbound_id INT;
    outbound_id BIGINT;
    source_index INT;
    country_id INT;
    submission TIMESTAMPTZ;
    opening TIMESTAMPTZ;
    closing TIMESTAMPTZ;
    statuses TEXT[] := ARRAY['In Review', 'Pending Interview', 'Accepted', 'Rejected', 'Withdrawn'];
    chosen_status TEXT;
BEGIN
    IF public.is_ku_coordinator() IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Only KU coordinators can generate testing applications';
    END IF;
    PERFORM 1 FROM public.testing WHERE id = 1 AND enabled IS TRUE FOR UPDATE;
    IF NOT FOUND OR public.get_maintenance_mode() IS DISTINCT FROM FALSE
       OR public.is_testing_record('exchange_cycle', requested_cycle_id::TEXT) IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Choose a testing cycle while testing mode is on and maintenance mode is off';
    END IF;
    SELECT * INTO cycle_row FROM public.exchange_cycle WHERE id = requested_cycle_id;
    opening := cycle_row.application_o AT TIME ZONE 'UTC';
    closing := LEAST(cycle_row.application_c AT TIME ZONE 'UTC', now());
    IF opening IS NULL OR closing IS NULL OR opening > closing THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'The testing cycle needs an open application window';
    END IF;
    IF EXISTS (SELECT 1 FROM public.inboundapplication WHERE semester_applied_for = requested_cycle_id AND first_name = 'Graph demo') THEN
        RETURN;
    END IF;
    SELECT array_agg(partner.university_id ORDER BY partner.university_id) INTO universities
    FROM public.partneruniversity AS partner WHERE partner.available AND partner.deleted_at IS NULL AND partner.university_id <> 4;
    SELECT array_agg(id ORDER BY id) INTO countries FROM public.country WHERE name <> 'Kuwait';
    IF COALESCE(cardinality(universities), 0) = 0 OR COALESCE(cardinality(countries), 0) = 0 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Add a partner university and a country before generating testing applications';
    END IF;
    FOREACH university_id IN ARRAY universities LOOP
        LOOP
            generated_coordinator_id := 1000000000 + floor(random() * 1000000000)::INT;
            EXIT WHEN NOT EXISTS (SELECT 1 FROM public.coordinator AS coordinator WHERE coordinator.coordinator_id = generated_coordinator_id);
        END LOOP;
        INSERT INTO public.coordinator(coordinator_id, name, email, university, email_accepted)
        VALUES (generated_coordinator_id, 'Graph demo coordinator', 'graph-' || generated_coordinator_id || '@example.invalid', university_id, TRUE);
        coordinator_ids := array_append(coordinator_ids, generated_coordinator_id);
    END LOOP;
    FOR sample IN 1..80 LOOP
        source_index := 1 + floor(random() * cardinality(universities))::INT;
        country_id := countries[1 + floor(random() * cardinality(countries))::INT];
        chosen_status := statuses[CASE WHEN sample <= 5 THEN sample ELSE 1 + floor(random() * 5)::INT END];
        submission := opening + (closing - opening) * random();
        LOOP
            inbound_id := 1000000000 + floor(random() * 1000000000)::INT;
            EXIT WHEN NOT EXISTS (SELECT 1 FROM public.inboundapplication WHERE application_id = inbound_id);
        END LOOP;
        LOOP
            nomination_id := 1000000000 + floor(random() * 1000000000)::BIGINT;
            EXIT WHEN NOT EXISTS (SELECT 1 FROM public.studentnominations WHERE id = nomination_id);
        END LOOP;
        INSERT INTO public.studentnominations(id, coordinator_id, student_name, student_email, semester, created_at)
        VALUES (nomination_id, coordinator_ids[source_index], 'Graph demo incoming ' || sample,
            'graph-in-' || inbound_id || '@example.invalid', requested_cycle_id, opening);
        INSERT INTO public.inboundapplication(application_id, first_name, last_name, email, nationality,
            semester_applied_for, nomination_id, application_status, approval_type, submitted_at, created_at, tos)
        VALUES (inbound_id, 'Graph demo', 'Incoming ' || sample, 'graph-in-' || inbound_id || '@example.invalid', country_id,
            requested_cycle_id, nomination_id, chosen_status, CASE WHEN chosen_status = 'Accepted' THEN 'Conditional' END, submission, submission, TRUE);
        LOOP
            outbound_id := floor(extract(epoch FROM clock_timestamp()) * 1000)::BIGINT * 1000 + floor(random() * 1000)::BIGINT;
            EXIT WHEN NOT EXISTS (SELECT 1 FROM public.outboundapplication WHERE application_id = outbound_id);
        END LOOP;
        INSERT INTO public.outboundapplication(application_id, first_name, last_name, nationality, semester_applied_for,
            university_id, application_status, submitted_at, created_at, gpa, credits_passed, tos)
        VALUES (outbound_id, 'Graph demo', 'Outgoing ' || sample, country_id, requested_cycle_id, universities[source_index],
            CASE WHEN chosen_status = 'Accepted' AND sample % 2 = 0 THEN 'Approved' ELSE chosen_status END,
            submission, submission, round((3 + random())::NUMERIC, 2), 60 + floor(random() * 43)::INT, TRUE);
    END LOOP;
END;
$$;
REVOKE ALL ON FUNCTION public.seed_testing_cycle_applications(INT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.seed_testing_cycle_applications(INT) TO authenticated;

CREATE OR REPLACE FUNCTION public.modify_outbound_application(
    requested_application_id BIGINT,
    requested_changes JSONB
)
RETURNS public.outboundapplication
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    -- Only the owner stays with the application. Documents, the semester and the preferred
    -- university are checked separately below.
    editable_fields CONSTANT TEXT[] := ARRAY[
        'first_name', 'middle_name', 'last_name', 'gender', 'birthdate',
        'nationality', 'passport_issuing_country', 'passport_number', 'passport_expiry_date',
        'civil_id_number', 'civil_id_expiry', 'phone_number', 'is_whatsapp_available',
        'major', 'current_year_of_study', 'gpa', 'credits_passed', 'expected_graduation_semester',
        'university_id', 'semester_applied_for'
    ];
    old_row public.outboundapplication;
    new_row public.outboundapplication;
    allowed_changes JSONB;
    new_application_id BIGINT;
    file_fields CONSTANT TEXT[] := ARRAY['civil_id_copy', 'passport_copy', 'transcript', 'profile_photo', 'cv'];
    file_field TEXT;
    file_path TEXT;
    file_prefix TEXT;
    editor_is_coordinator BOOLEAN := public.is_ku_coordinator();
BEGIN
    IF public.get_maintenance_mode() IS DISTINCT FROM FALSE
       OR (
            public.is_testing_mode_enabled() IS TRUE
            AND NOT public.is_testing_record('outboundapplication', requested_application_id::TEXT)
        ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '42501',
            MESSAGE = 'This application cannot be changed in the current mode';
    END IF;

    SELECT * INTO old_row
    FROM public.outboundapplication
    WHERE application_id = requested_application_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Application not found';
    END IF;

    IF NOT editor_is_coordinator AND NOT EXISTS (
        SELECT 1
        FROM public.kustudentauth AS student
        WHERE student.student_id = old_row.student_id
          AND student.user_id = auth.uid()
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '42501',
            MESSAGE = 'Only the student who applied or a KU coordinator can edit this application';
    END IF;

    IF old_row.application_status NOT IN ('Submitted', 'In Review', 'Pending Interview') THEN
        RAISE EXCEPTION 'Only an application awaiting a decision can be edited';
    END IF;

    SELECT COALESCE(jsonb_object_agg(key, value), '{}'::JSONB)
    INTO allowed_changes
    FROM jsonb_each(COALESCE(requested_changes, '{}'::JSONB))
    WHERE key = ANY(editable_fields);

    -- A new document must already be uploaded into this version's own folder; otherwise any
    -- path, including another student's file, could be attached to the application.
    FOREACH file_field IN ARRAY file_fields LOOP
        file_path := requested_changes ->> file_field;
        CONTINUE WHEN file_path IS NULL OR file_path IS NOT DISTINCT FROM (to_jsonb(old_row) ->> file_field);
        file_prefix := old_row.student_id::TEXT || '/' || old_row.application_id::TEXT || '/' || file_field || '/';
        IF left(file_path, length(file_prefix)) <> file_prefix
           OR NOT EXISTS (
                SELECT 1 FROM storage.objects
                WHERE bucket_id = 'outbound-application-files' AND name = file_path
            ) THEN
            RAISE EXCEPTION USING
                ERRCODE = '22023',
                MESSAGE = format('The new %s was not uploaded for this application', replace(file_field, '_', ' '));
        END IF;
        allowed_changes := allowed_changes || jsonb_build_object(file_field, file_path);
    END LOOP;

    -- Same shape as the ids the student portal creates: milliseconds followed by three digits.
    LOOP
        new_application_id := floor(extract(epoch FROM clock_timestamp()) * 1000)::BIGINT * 1000
            + 100 + floor(random() * 900)::BIGINT;
        EXIT WHEN NOT EXISTS (
            SELECT 1 FROM public.outboundapplication WHERE application_id = new_application_id
        );
    END LOOP;

    new_row := jsonb_populate_record(old_row, allowed_changes);

    -- The same rules a new application meets: a semester still taking applications and a
    -- partner university that is available. Keeping the current choice is always allowed.
    IF new_row.semester_applied_for IS DISTINCT FROM old_row.semester_applied_for
       AND NOT EXISTS (
            SELECT 1 FROM public.exchange_cycle AS cycle
            WHERE cycle.id = new_row.semester_applied_for
              AND cycle.application_c >= now()
        ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '22023',
            MESSAGE = 'Choose a KU semester that is still accepting applications';
    END IF;
    IF new_row.university_id IS DISTINCT FROM old_row.university_id
       AND NOT EXISTS (
            SELECT 1 FROM public.partneruniversity AS university
            WHERE university.university_id = new_row.university_id
              AND university.available IS TRUE
        ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '22023',
            MESSAGE = 'Choose an available partner university';
    END IF;
    new_row.application_id := new_application_id;
    new_row.original_application_id := COALESCE(old_row.original_application_id, old_row.application_id);
    new_row.status_updated_at := now();

    -- The old row leaves the one-application-per-nomination indexes before its copy enters them.
    PERFORM set_config('app.application_review', 'true', true);
    UPDATE public.outboundapplication
    SET application_status = 'Modified', status_updated_at = now()
    WHERE application_id = old_row.application_id;

    INSERT INTO public.outboundapplication
    SELECT (new_row).*
    RETURNING * INTO new_row;

    -- Keep the old version's proposed courses as evidence while its edited copy starts
    -- with the same list, ready for the student's next changes.
    INSERT INTO public.outbound_course_choices(application_id, subject_code, course_display_code, course_title, credits, created_at, updated_at)
    SELECT new_row.application_id, subject_code, course_display_code, course_title, credits, created_at, updated_at
    FROM public.outbound_course_choices WHERE application_id = old_row.application_id;

    -- The student's inbox, alternative offers and the coordinator's history follow the
    -- current version.
    UPDATE public.updates
    SET outbound_application_id = new_row.application_id
    WHERE outbound_application_id = old_row.application_id;

    UPDATE public.outbound_offers
    SET application_id = new_row.application_id
    WHERE application_id = old_row.application_id;

    INSERT INTO public.application_status_log(application_id, old_status, new_status, reason)
    VALUES (
        old_row.application_id,
        old_row.application_status,
        'Modified',
        format('Edited by %s; replaced by application %s',
            CASE WHEN editor_is_coordinator THEN 'a KU coordinator' ELSE 'the student' END,
            new_row.application_id)
    );

    RETURN new_row;
END;
$$;

REVOKE ALL ON FUNCTION public.modify_outbound_application(BIGINT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.modify_outbound_application(BIGINT, JSONB) TO authenticated;

